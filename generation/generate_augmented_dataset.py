PROMPT_TEMPLATE = f"""You are an expert Requirements Engineer. Your task is to reverse-engineer Software Requirements Specifications (SRS) from an Architecture Decision Record (ADR).
You must match the exact high quality, structure, and tone of my examples below.

{FEW_SHOT_EXAMPLES}

Now, read the following ADR and generate exactly {VARIATIONS_PER_ADR} DIFFERENT variations of the SRS that could have led to this decision.
Vary the tone slightly for each variation (e.g., one very formal enterprise style, one agile/startup style, one heavily focused on security, one highly technical, etc.), but keep the 3-point structure (Business Need, Functional, Non-Functional).

SEPARATE EACH VARIATION WITH THE EXACT STRING: "===VARIATION==="
Do not output anything else.

ORIGINAL ADR:
----------------
{{adr_text}}
----------------
"""

def generate_variations(adr_text):
    prompt = PROMPT_TEMPLATE.format(adr_text=adr_text)
    data = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False
    }
    
    req = urllib.request.Request(OLLAMA_URL, data=json.dumps(data).encode("utf-8"), headers={"Content-Type": "application/json"})
    
    try:
        with urllib.request.urlopen(req) as response:
            result = json.loads(response.read().decode("utf-8"))
            return result.get("response", "").strip()
    except Exception as e:
        print(f"Error querying Ollama: {e}")
        return None

def main():
    print(f"Starting Large-Scale Dataset Generation with Qwen Data Augmentation.")
    print(f"Output will be saved to {OUTPUT_FILE}")
    
    files_to_process = []
    for d in DIRS_TO_SCAN:
        for root, dirs, files in os.walk(d):
            for file in files:
                if file.endswith(".md"):
                    files_to_process.append(os.path.join(root, file))
                    
    print(f"Found {len(files_to_process)} ADR markdown files.")
    
    total_generated = 0
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as out_f:
        for i, filepath in enumerate(files_to_process):
            print(f"[{i+1}/{len(files_to_process)}] Processing: {os.path.basename(filepath)}...", end=" ", flush=True)
            
            try:
                with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read().strip()
            except Exception as e:
                print(f"File read error.")
                continue
                
            if len(content) < 150:
                print("Skipped (Too short)")
                continue
                
            # Limit ADR text size to prevent context overflow
            content_snippet = content[:5000]
            
            response = generate_variations(content_snippet)
            if not response:
                print("Skipped (Ollama error)")
                continue
                
            # Parse variations
            variations = [v.strip() for v in response.split("===VARIATION===") if v.strip()]
            
            if len(variations) == 0:
                print("Skipped (No variations parsed)")
                continue
                
            for srs_variation in variations:
                json_record = {
                    "instruction": INSTRUCTION,
                    "input": srs_variation,
                    "output": content # The full original ADR
                }
                out_f.write(json.dumps(json_record) + "\n")
                total_generated += 1
                
            print(f"Success! Generated {len(variations)} variations. (Total so far: {total_generated})")
            
    print(f"\nDone! Successfully generated {total_generated} high-quality training pairs.")

if __name__ == "__main__":
    main()
